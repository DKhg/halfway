CREATE TABLE settlement (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id               BIGINT NOT NULL UNIQUE REFERENCES room (id),
    payer_participant_id  BIGINT NOT NULL REFERENCES participant (id),
    payer_bank            VARCHAR(50),
    payer_account_number  VARCHAR(50),
    created_at            TIMESTAMP NOT NULL,
    updated_at            TIMESTAMP NOT NULL
);

CREATE TABLE settlement_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id  BIGINT NOT NULL REFERENCES settlement (id),
    name           VARCHAR(50) NOT NULL,
    amount         INTEGER NOT NULL,
    created_at     TIMESTAMP NOT NULL,
    updated_at     TIMESTAMP NOT NULL
);

CREATE TABLE settlement_item_member (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_item_id   BIGINT NOT NULL REFERENCES settlement_item (id),
    participant_id       BIGINT NOT NULL REFERENCES participant (id),
    created_at           TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_settlement_item_member_item_participant
    ON settlement_item_member (settlement_item_id, participant_id);

COMMENT ON TABLE settlement IS '방 1개당 1개, 정산을 먼저 시작(선점)한 결제자와 계좌 정보';
COMMENT ON COLUMN settlement.room_id IS '정산이 속한 방';
COMMENT ON COLUMN settlement.payer_participant_id IS '결제자로 선점한 참여자 (선착순, 이후 변경 불가)';
COMMENT ON COLUMN settlement.payer_bank IS '결제자 은행명 (토스 송금 딥링크 자동입력용)';
COMMENT ON COLUMN settlement.payer_account_number IS '결제자 계좌번호';

COMMENT ON TABLE settlement_item IS '정산 항목 (예: 1차 고기·식사)';
COMMENT ON COLUMN settlement_item.settlement_id IS '항목이 속한 정산';
COMMENT ON COLUMN settlement_item.name IS '항목 이름';
COMMENT ON COLUMN settlement_item.amount IS '항목 금액(원)';

COMMENT ON TABLE settlement_item_member IS '항목을 같이 나눠 낸 참여자';
COMMENT ON COLUMN settlement_item_member.settlement_item_id IS '대상 항목';
COMMENT ON COLUMN settlement_item_member.participant_id IS '같이 낸 참여자';
