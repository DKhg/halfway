CREATE TABLE station_travel_time (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_station_id BIGINT NOT NULL REFERENCES station (id),
    to_station_id   BIGINT NOT NULL REFERENCES station (id),
    minutes         SMALLINT NOT NULL,
    transfers       SMALLINT NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_station_travel_time_from_to ON station_travel_time (from_station_id, to_station_id);

COMMENT ON TABLE station_travel_time IS '역 간 최단 이동시간 (다익스트라 계산 결과, 전량 재계산되는 파생 데이터)';
COMMENT ON COLUMN station_travel_time.from_station_id IS '출발역';
COMMENT ON COLUMN station_travel_time.to_station_id IS '도착역';
COMMENT ON COLUMN station_travel_time.minutes IS '최단 이동시간(분)';
COMMENT ON COLUMN station_travel_time.transfers IS '최단 경로 상 환승 횟수';
