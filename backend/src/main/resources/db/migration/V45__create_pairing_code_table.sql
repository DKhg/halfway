CREATE TABLE pairing_code (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(4) NOT NULL,
    user_id     UUID NOT NULL REFERENCES users (id),
    expires_at  TIMESTAMP NOT NULL,
    used_at     TIMESTAMP,
    created_at  TIMESTAMP NOT NULL,
    updated_at  TIMESTAMP NOT NULL
);

CREATE INDEX ix_pairing_code_code ON pairing_code (code);
CREATE INDEX ix_pairing_code_user_id ON pairing_code (user_id);

COMMENT ON TABLE pairing_code IS 'iOS 홈 화면 PWA 설치 시 끊기는 브라우저 세션의 익명 식별자를 이어주기 위한 1회용 4자리 코드';
COMMENT ON COLUMN pairing_code.id IS '내부 식별자. 외부엔 노출하지 않음 (교환은 code로만)';
COMMENT ON COLUMN pairing_code.code IS '4자리 숫자 코드(0000~9999). 동시에 활성 상태인 코드끼리만 안 겹치면 되므로 유니크 제약 대신 발급 시 애플리케이션에서 충돌 검사';
COMMENT ON COLUMN pairing_code.user_id IS '이 코드로 복원할 대상 사용자';
COMMENT ON COLUMN pairing_code.expires_at IS '만료 시각 (발급 후 15분)';
COMMENT ON COLUMN pairing_code.used_at IS '교환(사용) 성공한 시각. null이면 아직 미사용';
