CREATE TABLE place_custom_option (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id             BIGINT NOT NULL REFERENCES room (id),
    category            VARCHAR(20) NOT NULL,
    place_id            VARCHAR(255) NOT NULL,
    place_name          VARCHAR(255) NOT NULL,
    road_address_name   VARCHAR(255),
    place_url           VARCHAR(255),
    walk_minutes        INTEGER,
    created_at          TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_place_custom_option_room_category_place
    ON place_custom_option (room_id, category, place_id);

COMMENT ON TABLE place_custom_option IS '참여자가 추천 5개 외에 직접 검색해서 추가한 가게 후보';
COMMENT ON COLUMN place_custom_option.room_id IS '이 후보가 속한 방';
COMMENT ON COLUMN place_custom_option.category IS '가게 대분류 (FOOD/CAFE)';
COMMENT ON COLUMN place_custom_option.place_id IS '카카오 로컬 API 장소 id. 추천 후보와 동일한 체계로 투표 집계에 사용';
COMMENT ON COLUMN place_custom_option.place_name IS '가게 이름 (추가 시점 스냅샷)';
COMMENT ON COLUMN place_custom_option.road_address_name IS '도로명 주소 (추가 시점 스냅샷)';
COMMENT ON COLUMN place_custom_option.place_url IS '카카오맵 장소 상세 페이지 링크 (추가 시점 스냅샷)';
COMMENT ON COLUMN place_custom_option.walk_minutes IS '확정 역에서 도보 소요시간(분), 거리 정보 없으면 null (추가 시점 스냅샷)';
