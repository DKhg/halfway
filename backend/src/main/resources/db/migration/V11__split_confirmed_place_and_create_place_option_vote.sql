ALTER TABLE room RENAME COLUMN confirmed_place_name TO confirmed_food_place_name;
ALTER TABLE room ADD COLUMN confirmed_cafe_place_name VARCHAR(255);

COMMENT ON COLUMN room.confirmed_food_place_name IS '확정된 약속 음식점 이름';
COMMENT ON COLUMN room.confirmed_cafe_place_name IS '확정된 약속 카페 이름';

CREATE TABLE place_option_vote (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL REFERENCES room (id),
    participant_id  BIGINT NOT NULL REFERENCES participant (id),
    category        VARCHAR(20) NOT NULL,
    place_name      VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_place_option_vote_room_participant_category_name
    ON place_option_vote (room_id, participant_id, category, place_name);

COMMENT ON TABLE place_option_vote IS '참여자가 가게 후보(음식점/카페)에 괜찮다고 체크한 기록';
COMMENT ON COLUMN place_option_vote.room_id IS '체크가 속한 방';
COMMENT ON COLUMN place_option_vote.participant_id IS '체크한 참여자';
COMMENT ON COLUMN place_option_vote.category IS '체크 대상 가게의 대분류 (FOOD/CAFE)';
COMMENT ON COLUMN place_option_vote.place_name IS '체크 대상 가게 이름 (더미 데이터 단계라 ID 없이 이름으로 식별)';
