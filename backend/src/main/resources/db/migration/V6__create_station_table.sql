CREATE TABLE station (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50) NOT NULL,
    line            VARCHAR(20) NOT NULL,
    lat             DOUBLE PRECISION,
    lng             DOUBLE PRECISION,
    is_meeting_spot BOOLEAN NOT NULL DEFAULT TRUE,
    area_type       VARCHAR(20),
    has_indoor      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_station_name_line ON station (name, line);

COMMENT ON TABLE station IS '지하철 역 (역x노선 단위)';
COMMENT ON COLUMN station.name IS '역 이름';
COMMENT ON COLUMN station.line IS '노선명';
COMMENT ON COLUMN station.lat IS '위도 (아직 미적재)';
COMMENT ON COLUMN station.lng IS '경도 (아직 미적재)';
COMMENT ON COLUMN station.is_meeting_spot IS '중간지점 후보 가능 여부';
COMMENT ON COLUMN station.area_type IS '번화가/조용한 동네 (BUSY/QUIET)';
COMMENT ON COLUMN station.has_indoor IS '지하상가·복합몰 인접 여부';
