CREATE TABLE place_candidate (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL REFERENCES room (id),
    station_name    VARCHAR(255) NOT NULL,
    rank            SMALLINT NOT NULL,
    fairness_score  SMALLINT NOT NULL,
    max_minutes     SMALLINT NOT NULL,
    sum_minutes     SMALLINT NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE TABLE place_candidate_time (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id    BIGINT NOT NULL REFERENCES place_candidate (id),
    participant_id  BIGINT NOT NULL REFERENCES participant (id),
    minutes         SMALLINT NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_place_candidate_time_candidate_participant
    ON place_candidate_time (candidate_id, participant_id);

CREATE TABLE place_vote (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id    BIGINT NOT NULL REFERENCES place_candidate (id),
    participant_id  BIGINT NOT NULL REFERENCES participant (id),
    created_at      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_place_vote_candidate_participant
    ON place_vote (candidate_id, participant_id);

COMMENT ON TABLE place_candidate IS '투표 시작 시점에 고정된 중간지점 후보 스냅샷';
COMMENT ON COLUMN place_candidate.room_id IS '후보가 속한 방';
COMMENT ON COLUMN place_candidate.station_name IS '후보 역 이름';
COMMENT ON COLUMN place_candidate.rank IS '투표 시작 시점 순위 (1~3)';
COMMENT ON COLUMN place_candidate.fairness_score IS '투표 시작 시점 공평도 스냅샷';
COMMENT ON COLUMN place_candidate.max_minutes IS '투표 시작 시점 최장 이동시간(분) 스냅샷';
COMMENT ON COLUMN place_candidate.sum_minutes IS '투표 시작 시점 총 이동시간(분) 스냅샷';

COMMENT ON TABLE place_candidate_time IS '후보별 참여자 소요시간 스냅샷 (투표 시작 시점 고정)';
COMMENT ON COLUMN place_candidate_time.candidate_id IS '대상 후보';
COMMENT ON COLUMN place_candidate_time.participant_id IS '대상 참여자';
COMMENT ON COLUMN place_candidate_time.minutes IS '해당 참여자의 후보까지 소요시간(분)';

COMMENT ON TABLE place_vote IS '참여자가 후보에 괜찮다고 체크한 기록';
COMMENT ON COLUMN place_vote.candidate_id IS '체크한 후보';
COMMENT ON COLUMN place_vote.participant_id IS '체크한 참여자';
