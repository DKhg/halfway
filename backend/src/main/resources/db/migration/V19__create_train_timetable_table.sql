CREATE TABLE train_timetable (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id           BIGINT NOT NULL REFERENCES station (id),
    train_no             VARCHAR(10) NOT NULL,
    week_tag             SMALLINT NOT NULL,
    inout_tag            SMALLINT NOT NULL,
    arrive_minute        SMALLINT NOT NULL,
    leave_minute         SMALLINT,
    origin_station_name  VARCHAR(50) NOT NULL,
    dest_station_name    VARCHAR(50) NOT NULL,
    express_yn           VARCHAR(1),
    created_at           TIMESTAMP NOT NULL,
    updated_at           TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_train_timetable_station_train_week ON train_timetable (station_id, train_no, week_tag);
CREATE INDEX ix_train_timetable_train_week ON train_timetable (train_no, week_tag);
CREATE INDEX ix_train_timetable_station_week_inout ON train_timetable (station_id, week_tag, inout_tag);

