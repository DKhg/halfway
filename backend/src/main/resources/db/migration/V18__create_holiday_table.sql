CREATE TABLE holiday (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date DATE NOT NULL,
    name         VARCHAR(50) NOT NULL,
    created_at   TIMESTAMP NOT NULL,
    updated_at   TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_holiday_date ON holiday (holiday_date);

COMMENT ON TABLE holiday IS '법정 공휴일 (한국천문연구원 특일정보 API 적재). 막차 계산의 요일타입(평일/토요일/일요일·공휴일) 판정에 사용';
COMMENT ON COLUMN holiday.holiday_date IS '공휴일 날짜';
COMMENT ON COLUMN holiday.name IS '공휴일 이름 (예: 설날, 추석, 대체공휴일)';
