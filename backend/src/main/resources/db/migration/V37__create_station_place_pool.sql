CREATE TABLE station_place_pool (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name        VARCHAR(50) NOT NULL,
    category            VARCHAR(20) NOT NULL,
    place_id            VARCHAR(255) NOT NULL,
    place_name          VARCHAR(255) NOT NULL,
    road_address_name   VARCHAR(255),
    place_url           VARCHAR(255),
    walk_minutes        INTEGER,
    comment             VARCHAR(20),
    created_at          TIMESTAMP NOT NULL,
    updated_at          TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX ux_station_place_pool_station_category_place
    ON station_place_pool (station_name, category, place_id);

COMMENT ON TABLE station_place_pool IS '역별로 쌓이는 가게 후보 풀. 방이 삭제돼도 안 지워지며, 같은 역에서 모임을 여는 다음 방들에 제안용으로 노출';
COMMENT ON COLUMN station_place_pool.station_name IS '역 이름 (room.confirmed_station_name과 동일 체계)';
COMMENT ON COLUMN station_place_pool.category IS '가게 대분류 (FOOD/CAFE)';
COMMENT ON COLUMN station_place_pool.place_id IS '카카오 로컬 API 장소 id';
COMMENT ON COLUMN station_place_pool.place_name IS '가게 이름 (최초 추가 시점 스냅샷)';
COMMENT ON COLUMN station_place_pool.road_address_name IS '도로명 주소 (최초 추가 시점 스냅샷)';
COMMENT ON COLUMN station_place_pool.place_url IS '카카오맵 장소 상세 페이지 링크 (최초 추가 시점 스냅샷)';
COMMENT ON COLUMN station_place_pool.walk_minutes IS '역에서 도보 소요시간(분), 거리 정보 없으면 null (최초 추가 시점 스냅샷)';
COMMENT ON COLUMN station_place_pool.comment IS '최초로 추가한 사람이 남긴 짧은 한줄평 (선택, 최대 20자). 이후 같은 가게가 또 추가돼도 덮어쓰지 않음';
