const DEFAULT_COLOR = '#8a8a8a'

export function getLineColor(line) {
  return LINE_COLORS[line] ?? DEFAULT_COLOR
}

export function getLineLabel(line) {
  if (typeof line !== 'string') {
    return ''
  }
  if (LINE_LABELS[line]) {
    return LINE_LABELS[line]
  }
  const digitMatch = line.match(/^(\d+)호선$/)
  return digitMatch ? digitMatch[1] : line.slice(0, 2)
}
